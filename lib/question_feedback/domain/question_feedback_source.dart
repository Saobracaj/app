/// Откуда пользователь пожаловался на вопрос.
///
/// Ключ уходит в текст сообщения разработчику как есть (`Report · discussion`),
/// поэтому это стабильная строка, а не локализуемая подпись: по ней разработчик
/// понимает, какая именно вкладка вопроса вызвала жалобу.
enum QuestionFeedbackSource {
  /// Вкладка «Обсуждение» (публичные комментарии).
  discussion('discussion'),

  /// Вкладка «Объяснение» (редакторский комментарий к вопросу).
  explanation('explanation'),

  /// Вкладка «Конспект» (выдержки из конспекта категории).
  summary('summary'),

  /// Вкладка «Спросить AI» (предгенерированное объяснение).
  askAi('ask_ai');

  const QuestionFeedbackSource(this.key);

  final String key;
}

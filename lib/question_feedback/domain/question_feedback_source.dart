/// Откуда пользователь пожаловался на контент.
///
/// Ключ уходит в текст сообщения разработчику как есть (`Report · summary`),
/// поэтому это стабильная строка, а не локализуемая подпись: по ней разработчик
/// понимает, какое именно место приложения вызвало жалобу.
enum QuestionFeedbackSource {
  /// Вкладка «Объяснение» (редакторский комментарий к вопросу).
  explanation('explanation'),

  /// Вкладка «Конспект» (выдержки из конспекта категории под вопросом).
  summary('summary'),

  /// Полный конспект категории (экран `/konspekt`).
  konspekt('konspekt');

  const QuestionFeedbackSource(this.key);

  final String key;
}

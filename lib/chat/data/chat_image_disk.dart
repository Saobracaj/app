import 'dart:typed_data';

/// Дисковая половина кэша картинок чата.
///
/// Вынесена за условный импорт, потому что `dart:io` в вебе не собирается
/// вовсе: там реализацией служит заглушка, и кэш остаётся только в памяти
/// (плюс кэш самого браузера по HTTP-заголовкам).
abstract class ChatImageDisk {
  /// Байты вложения из кэша, или `null`, если их там нет.
  Future<Uint8List?> read(String id);

  /// Положить байты в кэш. Ошибки проглатываются: кэш — оптимизация.
  Future<void> write(String id, Uint8List bytes);

  /// Забыть всё.
  Future<void> clear();
}
